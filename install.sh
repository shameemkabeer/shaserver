#!/usr/bin/env bash
# PiBoard installer. Run from the piboard directory as your normal user (not root).
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"
HERE="$(pwd)"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*"; exit 1; }

[ "$(id -u)" -ne 0 ] || die "Run as your normal user, not root."
command -v docker >/dev/null || die "Docker is not installed."
docker compose version >/dev/null 2>&1 || die "The docker compose plugin is missing."
docker info >/dev/null 2>&1 || die "Cannot talk to Docker. Is your user in the 'docker' group? (sudo usermod -aG docker \$USER, then log in again)"

# ---- .env -------------------------------------------------------------------
if [ -f .env ]; then
  say "Keeping existing .env"
else
  TS_IP="${TAILSCALE_IP:-}"
  [ -n "$TS_IP" ] || TS_IP="$(tailscale ip -4 2>/dev/null | head -n1 || true)"
  [ -n "$TS_IP" ] || TS_IP="$(ip -4 -o addr show tailscale0 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1 || true)"
  [ -n "$TS_IP" ] || die "Could not detect the Tailscale IP. Re-run as: TAILSCALE_IP=100.x.y.z ./install.sh"
  TZ_NAME="$(cat /etc/timezone 2>/dev/null || timedatectl show -p Timezone --value 2>/dev/null || echo UTC)"
  cat > .env <<ENV
# Generated by install.sh on $(date -I). No secrets in here.
PIBOARD_HOME=$HERE
PIBOARD_PORT=${PIBOARD_PORT:-8088}
LOCAL_IP=127.0.0.1
TAILSCALE_IP=$TS_IP
PUID=$(id -u)
PGID=$(id -g)
DOCKER_GID=$(getent group docker | cut -d: -f3)
TZ=$TZ_NAME
ENV
  say "Wrote .env (Tailscale IP $TS_IP)"
fi
# shellcheck disable=SC1091
set -a; . ./.env; set +a

mkdir -p apps data screensaver
chmod 700 data

# ---- boot-order safety for the Tailscale bind ------------------------------
# Containers that publish on the Tailscale IP fail to start if Docker comes up
# before tailscale0 has its address. net.ipv4.ip_nonlocal_bind=1 lets them bind
# anyway (traffic flows once Tailscale is up). It does NOT open anything to the LAN.
if [ "$(cat /proc/sys/net/ipv4/ip_nonlocal_bind)" != "1" ]; then
  warn "Recommended: allow binding to the Tailscale IP before tailscale0 is up (avoids containers failing at boot)."
  read -r -p "    Write /etc/sysctl.d/99-piboard.conf with net.ipv4.ip_nonlocal_bind=1 (needs sudo)? [Y/n] " a
  if [[ ! "$a" =~ ^[Nn] ]]; then
    echo "net.ipv4.ip_nonlocal_bind=1" | sudo tee /etc/sysctl.d/99-piboard.conf >/dev/null
    sudo sysctl -q -p /etc/sysctl.d/99-piboard.conf
    say "Enabled ip_nonlocal_bind"
  fi
fi

# ---- build & start ----------------------------------------------------------
say "Building and starting PiBoard (first build takes a few minutes)..."
docker compose up -d --build

say "Waiting for PiBoard to become ready..."
for _ in $(seq 1 60); do
  curl -fsS "http://127.0.0.1:${PIBOARD_PORT}/api/health" >/dev/null 2>&1 && break
  sleep 1
done
curl -fsS "http://127.0.0.1:${PIBOARD_PORT}/api/health" >/dev/null || die "PiBoard did not start. Check: docker logs piboard"

echo
say "PiBoard is running:"
echo "    http://${TAILSCALE_IP}:${PIBOARD_PORT}   (from your tailnet)"
echo "    http://$(hostname):${PIBOARD_PORT}       (MagicDNS)"
if [ -f data/setup.code ]; then
  echo
  say "First-run setup code: $(cat data/setup.code)"
  echo "    Open the URL above, enter the code and choose an admin password."
fi
echo
echo "Optional: kiosk on the HDMI display -> sudo ./kiosk/install-kiosk.sh"
